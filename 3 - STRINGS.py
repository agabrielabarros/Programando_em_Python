#FATIAMENTO DE STRINGS 
#RANGE DE STRINGS
#O fatiamento de strings é feito através do operador de colchetes [] e permite acessar partes específicas de uma string. A sintaxe básica para fatiar uma string é a seguinte
#string[inicio:fim:passo]
#onde:
#inicio: índice do primeiro caractere da substring
#fim: índice do último caractere da substring (não incluído)
#passo: intervalo entre os caracteres da substring
